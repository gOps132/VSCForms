// Verifies VSCForms' Form Schema against what WinForms ACTUALLY does at runtime.
//
// This is the only test that can catch a semantically-wrong-but-syntactically-valid
// patch. Every other tier checks that the code compiles and that the diff is minimal;
// none of them can tell you that `Location = new Point(500, 250)` put the control
// somewhere the designer would not have.
//
// Runs on Windows only, because instantiating System.Windows.Forms requires the
// Windows Desktop runtime. See scripts/run-windows-layout.sh.
//
// STAGING CONTRACT: this file is form-agnostic. The harness copies the Designer file
// under test plus two generated files into the same assembly: Shim.cs provides
// `VscformsLayoutHost.CreateForm()` for the copied form's NS/CLASS, and Stubs.cs
// (scripts/gen-layout-stubs.py) supplies event handlers and third-party types
// that live outside the Designer file. This file never names a form type and
// works for every fixture unmodified. It accepts the engine's parse response
// or the bare schema as its argument.
//
// Usage: VSCFormsLayoutCheck <schema.json> [scale-tolerance]
//        VSCFormsLayoutCheck --matrix <manifest.json>
//
// The matrix mode is the differential oracle's runtime half: it checks MANY forms in
// ONE process, each against its own schema, using the same comparison rules as the
// single-form mode. The permutation matrix is generated by
// scripts/gen-differential-matrix.py; the Windows driver is
// scripts/verify-differential-matrix.ps1.

using System.Globalization;
using System.Reflection;
using System.Text.Json;
using System.Windows.Forms;

internal static class Program
{
    private static int failures;

    private static int tolerance;

    private static int Main(string[] args)
    {
        if (args.Length >= 2 && args[0] == "--matrix")
        {
            // `--matrix <manifest> [--render <dir>] [--png]`
            //
            // The RECTANGLES are always written when a render directory is given: they are
            // small, and they are the half of the visual-parity check that can be
            // automated (does the canvas put each control where, and how big, the runtime
            // will put it?). The PNGs are opt-in with `--png`: they are the visual
            // reference for a comparison against the Visual Studio designer, and they are
            // an artifact rather than an assertion.
            string? renderDir = null;
            bool writePng = false;
            for (int i = 2; i + 1 < args.Length; i++)
            {
                if (args[i] == "--render") renderDir = args[i + 1];
                if (args[i] == "--png") writePng = true;
            }
            return RunMatrix(args[1], renderDir, writePng);
        }

        if (args.Length < 1)
        {
            Console.Error.WriteLine("usage: VSCFormsLayoutCheck <schema.json> [tolerance]");
            return 2;
        }
        if (args.Length >= 2 && int.TryParse(args[1],
                NumberStyles.Integer, CultureInfo.InvariantCulture, out int t) && t >= 0)
            tolerance = t;

        using var doc = JsonDocument.Parse(File.ReadAllText(args[0]));
        var schema = doc.RootElement;
        // The harness feeds the engine's parse response ({id, ok, schema});
        // accept the bare schema too so the checker stays runnable by hand.
        if (schema.TryGetProperty("schema", out var inner))
            schema = inner;

        var refuses = schema.GetProperty("analysis").GetProperty("refuses");
        bool refusedOnly = refuses.GetArrayLength() > 0;
        string reasons = string.Join(", ",
            refuses.EnumerateArray().Select(e => e.GetString()));

        // A refused form may not construct at all: localizable geometry lives in
        // the .resx, which the staged assembly does not have, so ApplyResources
        // throws. That is the parse tier's territory (it classified the refusal),
        // not a layout failure — report it loudly and stop. A modellable form
        // that cannot construct is a real failure and propagates.
        System.Windows.Forms.Form form = null!;
        try
        {
            form = VscformsLayoutHost.CreateForm();
        }
        catch (Exception ex) when (refusedOnly)
        {
            Console.WriteLine($"REFUSED ({reasons}) — runtime geometry is not " +
                "verifiable; refusal covered by parse tier");
            Console.WriteLine($"construction failed with: {ex.GetType().FullName}");
            return 0;
        }
        using var _ = form;

        // Isolate designer geometry from environment scaling. WinForms applies
        // AutoScale (Font/Dpi) on handle creation based on the runner's DPI vs the
        // file's AutoScaleDimensions — the same file then reports different Bounds
        // on different machines. VSCForms deliberately does not simulate scaling
        // (C3: read-only warning, no editing), so the harness must not fail for it:
        // freeze scaling before any handle exists and compare the verbatim values.
        form.AutoScaleMode = AutoScaleMode.None;
        // Force layout so every control has a real, final position.
        form.PerformLayout();

        Console.WriteLine($"form: {schema.GetProperty("form").GetProperty("name").GetString()}");
        Console.WriteLine($"declared clientSize: " +
            $"{schema.GetProperty("form").GetProperty("clientSize").GetProperty("width").GetInt32()}x" +
            $"{schema.GetProperty("form").GetProperty("clientSize").GetProperty("height").GetInt32()}");
        Console.WriteLine($"actual   clientSize: {form.ClientSize.Width}x{form.ClientSize.Height}");
        if (refusedOnly)
            Console.WriteLine("mode: presence-only (refused form — geometry lives outside the file)");
        Console.WriteLine();

        int checkedCount = Walk(schema.GetProperty("controls"), form.Controls, !refusedOnly);
        form.Dispose();

        Console.WriteLine();
        Console.WriteLine($"checked {checkedCount} control(s); {failures} failure(s)");

        if (failures == 0)
        {
            Console.WriteLine(refusedOnly
                ? "PASS — every schema control exists at runtime"
                : "PASS — schema geometry matches runtime geometry");
            return 0;
        }

        Console.WriteLine("FAIL — schema geometry disagrees with the real control tree");
        return 1;
    }

    /// <summary>
    /// The matrix mode: check every form in the manifest, each against its own schema.
    ///
    /// The manifest is a JSON array of { id, namespace, className, schema }. The form is
    /// found by REFLECTION over this assembly's types, because the matrix contains
    /// hundreds of forms and a hand-written factory for each would be absurd — and a
    /// generated factory would be a second thing that can be wrong.
    ///
    /// The comparison rules are the ones the single-form mode uses: same Walk, same
    /// tolerance, same AutoScale freeze. One copy of the rules, so the two tiers
    /// cannot drift apart.
    /// </summary>
    private static int RunMatrix(string manifestPath, string? renderDir, bool writePng)
    {
        using var doc = JsonDocument.Parse(File.ReadAllText(manifestPath));
        var entries = doc.RootElement.GetProperty("cases").EnumerateArray().ToList();

        var types = Assembly.GetExecutingAssembly().GetTypes();
        int checkedCount = 0;
        int caseFailures = 0;

        foreach (var entry in entries)
        {
            string id = entry.GetProperty("id").GetString()!;
            string ns = entry.GetProperty("namespace").GetString()!;
            string cls = entry.GetProperty("className").GetString()!;
            string schemaPath = entry.GetProperty("schema").GetString()!;

            using var schemaDoc = JsonDocument.Parse(File.ReadAllText(schemaPath));
            var schema = schemaDoc.RootElement;
            if (schema.TryGetProperty("schema", out var inner))
                schema = inner;

            var type = types.FirstOrDefault(t =>
                t.FullName == $"{ns}.{cls}" && !t.IsAbstract);
            if (type is null)
            {
                failures++;
                caseFailures++;
                Console.WriteLine($"  FAIL {id}: no type {ns}.{cls} in the assembly");
                continue;
            }

            Form form;
            try
            {
                form = (Form)Activator.CreateInstance(type)!;
            }
            catch (Exception ex)
            {
                failures++;
                caseFailures++;
                Console.WriteLine($"  FAIL {id}: the form could not be constructed " +
                    $"({ex.GetType().Name}: {ex.Message})");
                continue;
            }

            using (form)
            {
                form.AutoScaleMode = AutoScaleMode.None;
                form.PerformLayout();
                int before = failures;
                int n = Walk(schema.GetProperty("controls"), form.Controls, true);
                checkedCount += n;
                if (failures > before)
                {
                    caseFailures++;
                    Console.WriteLine($"  --- {id}: geometry disagrees with the runtime");
                }

                // The render happens inside the using block: the form must still be alive.
                if (renderDir is not null)
                    Render(form, id, renderDir, writePng);
            }
        }

        Console.WriteLine();
        Console.WriteLine($"matrix: {entries.Count} form(s), {checkedCount} control(s) checked, " +
            $"{caseFailures} case(s) with failures, {failures} failure(s) total");

        if (failures == 0)
        {
            Console.WriteLine("PASS — every matrix form matches the real runtime");
            return 0;
        }
        Console.WriteLine("FAIL — the matrix disagrees with the real control tree");
        return 1;
    }

    /// <summary>
    /// Render the form to a PNG and record where every control ended up.
    ///
    /// WHY THIS IS THE VISUAL REFERENCE
    ///   The Visual Studio WinForms designer hosts REAL controls and asks WinForms to paint
    ///   them, so the designer's pixels ARE the runtime's pixels (minus the designer's own
    ///   chrome: the grid, the selection handles, the tab strip's designer decoration). That
    ///   means a runtime render is a faithful reference image for a visual-parity check
    ///   against the designer — and it can be produced headlessly, for every matrix case, on
    ///   every CI run, with no Visual Studio and no GUI automation.
    ///
    ///   The recorded rectangles are the more useful half for automation: the canvas draws a
    ///   STYLISED box per control, so the parity question is not "do the pixels match" (they
    ///   never will — ADR 0006 says the canvas is a layout view, not a renderer) but "does
    ///   the canvas put the control where the runtime will put it, and at the size the
    ///   runtime will give it". The rectangles answer exactly that.
    ///
    ///   KNOWN LIMITATION: DrawToBitmap asks each control to draw itself with WM_PRINT, and
    ///   a control that does not implement it renders blank. A few WinForms controls are in
    ///   that class, so a render is a reference for the controls that DO paint, not a
    ///   pixel-perfect oracle for all of them. The rectangles are unaffected — they come
    ///   from the layout, not the painting.
    /// </summary>
    private static void Render(Form form, string id, string renderDir, bool writePng)
    {
        try
        {
            Directory.CreateDirectory(renderDir);

            var size = form.ClientSize;
            if (size.Width <= 0 || size.Height <= 0) return;

            if (writePng)
            {
                using var bmp = new Bitmap(size.Width, size.Height);
                form.DrawToBitmap(bmp, new Rectangle(0, 0, size.Width, size.Height));
                bmp.Save(Path.Combine(renderDir, id + ".png"),
                         System.Drawing.Imaging.ImageFormat.Png);
            }

            // The rectangles, in the same JSON shape the canvas's DOM metrics use, so the
            // two sides can be compared without a translation layer.
            var sb = new System.Text.StringBuilder();
            sb.Append("{\"id\":\"").Append(id).Append("\",\"clientSize\":{\"width\":")
              .Append(size.Width).Append(",\"height\":").Append(size.Height)
              .Append("},\"controls\":[");
            bool first = true;
            CollectRects(form.Controls, sb, ref first);
            sb.Append("]}");
            File.WriteAllText(Path.Combine(renderDir, id + ".json"), sb.ToString());
        }
        catch (Exception ex)
        {
            // A render failure must not fail the comparison: the geometry check is the
            // assertion; the render is the artifact.
            Console.WriteLine($"  note {id}: render failed ({ex.GetType().Name}: {ex.Message})");
        }
    }

    private static void CollectRects(Control.ControlCollection controls, System.Text.StringBuilder sb, ref bool first)
    {
        foreach (Control c in controls)
        {
            if (!first) sb.Append(',');
            first = false;
            sb.Append("{\"id\":\"").Append(c.Name).Append("\",\"type\":\"")
              .Append(c.GetType().Name).Append("\",\"x\":").Append(c.Left)
              .Append(",\"y\":").Append(c.Top)
              .Append(",\"width\":").Append(c.Width)
              .Append(",\"height\":").Append(c.Height)
              .Append(",\"text\":\"").Append(c.Text?.Replace("\\", "\\\\").Replace("\"", "\\\"") ?? "")
              .Append("\"}");
            CollectRects(c.Controls, sb, ref first);
        }
    }

    private static int Walk(JsonElement nodes, Control.ControlCollection controls, bool geometry)
    {
        int count = 0;
        foreach (var node in nodes.EnumerateArray())
        {
            string id = node.GetProperty("id").GetString()!;
            var props = node.GetProperty("properties");
            bool locked = node.TryGetProperty("locked", out var l) && l.GetBoolean();

            var found = FindByName(controls, id);
            if (found is null)
            {
                // Locked controls are not in the schema's modelled set only if they are absent;
                // present-but-locked still has to exist at runtime.
                Report(id, "control not found at runtime");
                continue;
            }

            count++;
            if (!geometry)
            {
                // Refused form: geometry lives outside the file (.resx, dock
                // engine), so existence at runtime is the whole check.
            }
            else
            {
                // A TabPage's geometry belongs to the TabControl, not to the file. The
                // designer writes the TabPage's Location/Size as it was at design time;
                // at runtime the TabControl lays the page out in its own display area.
                // Comparing them would report a divergence that says nothing about
                // VSCForms — and VSCForms deliberately does not simulate that layout
                // (ADR 0003: refuse rather than simulate). So the TabPage is checked for
                // EXISTENCE only, exactly like a control the runtime owns.
                bool tabPage = node.TryGetProperty("type", out var t)
                               && t.GetString() is string tn
                               && tn.EndsWith(".TabPage", StringComparison.Ordinal);

                if (!tabPage)
                {
                    Check(id, "Location.X", props.GetProperty("x").GetInt32(), found.Left);
                    Check(id, "Location.Y", props.GetProperty("y").GetInt32(), found.Top);
                }

                // Genuinely un-simulatable cases:
                // 1. TabPage: geometry is owned and laid out by the TabControl in its display area.
                // 2. MonthCalendar: runtime discretely snaps Size to the month calendar grid.
                // 3. Text-driven AutoSize controls (Label, LinkLabel, and CheckBox/RadioButton
                //    when AutoSize is true): runtime computes Width and Height from GDI font
                //    measurement of Text, which VSCForms does not simulate (ADR 0006).
                //
                // Leaf inputs (TextBox, ComboBox, DateTimePicker, NumericUpDown, TrackBar)
                // have font- or chrome-constrained heights (23 for 9pt text inputs, 45 for
                // TrackBar), but are NOT text-sized. The generator writes their exact runtime
                // size, so they are verified with NO EXCLUSIONS on either axis (#65).
                bool textDrivenAutoSize = found is Label or LinkLabel
                                          || (found is CheckBox or RadioButton &&
                                              found.GetType().GetProperty("AutoSize")?.GetValue(found) is bool b && b);
                bool gridSnapped = found is MonthCalendar;

                if (!textDrivenAutoSize && !gridSnapped && !tabPage)
                {
                    Check(id, "Size.Width", props.GetProperty("width").GetInt32(), found.Width);
                    Check(id, "Size.Height", props.GetProperty("height").GetInt32(), found.Height);
                }
            }

            if (node.TryGetProperty("children", out var children) && children.GetArrayLength() > 0)
                count += Walk(children, found.Controls, geometry);
        }

        return count;
    }

    private static Control? FindByName(Control.ControlCollection controls, string name)
    {
        foreach (Control c in controls)
        {
            if (c.Name == name) return c;
            var nested = FindByName(c.Controls, name);
            if (nested is not null) return nested;
        }
        return null;
    }

    private static void Check(string id, string what, int expected, int actual)
    {
        if (Math.Abs(expected - actual) > tolerance)
            Report(id, $"{what}: schema says {expected}, runtime is {actual}");
    }

    private static void Report(string id, string message)
    {
        failures++;
        Console.WriteLine($"  FAIL {id}: {message}");
    }
}